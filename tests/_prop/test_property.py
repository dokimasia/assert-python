class Kept(Recorder):
    """A recorder whose cleanups run when the test ends."""

    def __init__(self, collector: Collector) -> None:
        """Return a recorder whose cleanups run when the test of collector ends."""
        super().__init__()
        self._collector: Collector = collector

    @override
    def cleanup(self, fn: Callable[[], object]) -> None:
        """Register fn to run when the test ends."""
        self._collector.cleanup(fn)


def any_digit(c: Case) -> None:
    """Pass for every digit that the case generates under the label x."""
    c.draw(DIGITS, "x")


def below_five(c: Case) -> None:
    """Fail for a digit of 5 or more under the label x."""
    check.is_true(c, c.draw(DIGITS, "x") < 5, "x is below 5")


def a_digit(c: Case) -> None:
    """Check that the value under the label x is a digit."""
    check.is_true(c, c.draw(DIGITS, "x") < 10, "x is a digit")


def plus_one_below_five(c: Case) -> None:
    """Fail when the digit under the label x plus one is 5 or more."""
    check.is_true(c, c.draw(Mapped(DIGITS, lambda x: x + 1), "x") < 5, "x is below 5")


async def awaits_a_digit(c: Case) -> None:
    """Generate a digit under the label x after an await."""
    await asyncio.sleep(0)
    c.draw(DIGITS, "x")


def starts_with_seven(c: Case) -> None:
    """Fail when the generated byte string of up to four bytes starts with 7."""
    data = c.draw(Bytes(SequenceBounds(256, 0, 4)), "data")
    check.is_false(c, data[:1] == b"\x07", "the data does not start with 7")


def skips_every_case(c: Case) -> None:
    """Draw a digit under the label x, and skip the run."""
    c.draw(DIGITS, "x")
    c.skip("unsupported")


def property_of(seat: Seat, *options: Option) -> Property:
    """Return the property of options on seat.

    The property is hermetic, and its seed is 1. It does not have a store
    unless an option sets one.
    """
    return Property.of(
        seat, CALL, configure([hermetic(), seed(1), store(""), *options])
    )


def run_on(seat: Seat, body: PropertyBody, *options: Option) -> None:
    """Run body as the property of options on seat."""
    property_of(seat, *options).run(seat, Running.begin(seat, WHERE), body)


def first_detail(recorder: Recorder) -> dict[str, Any]:
    """Return the detail of the first failure that recorder received."""
    failures = recorder.failures
    return dict(failures[0].detail) if failures else {}


def notes(recorder: Recorder, call: Callable[[], object]) -> list[str]:
    """Return the text of each fault that recorder receives while call runs."""
    call()
    return [str(fault) for fault in recorder.faults]


def in_a_running_loop(call: Callable[[], object]) -> None:
    """Make call from a coroutine on a running event loop."""

    async def main() -> None:
        call()

    asyncio.run(main())


def stored_by_a_failure(directory: Path) -> str:
    """Write the entry of a failure of below_five into a store, and return its name.

    The recorder runs its cleanups after the run, so a later property can claim
    the entries.
    """
    recorder = Recorder()
    run_on(recorder, below_five, store(str(directory)))
    recorder.run_cleanups()
    [entry] = directory.iterdir()
    return entry.name


