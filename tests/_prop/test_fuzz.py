"""The spec of _prop/fuzz.py tests a property whose cases a fuzzer decodes."""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

from dokimi_assert import check
from dokimi_assert._matcher.seat import name_test
from dokimi_assert._prop.engine.choice import SequenceBounds
from dokimi_assert._prop.engine.generator import Bytes
from dokimi_assert._prop.environment import PROFILE_VARIABLE
from dokimi_assert._prop.forall import for_all
from dokimi_assert._prop.fuzz import fuzz
from dokimi_assert._prop.option import hermetic, on_result, seed, store
from dokimi_assert.seat import Collector, Recorder
from helpers import records

if TYPE_CHECKING:
    import pytest

    from dokimi_assert._prop.case import Case
    from dokimi_assert._prop.detail import Result

#: The variable that a mutation run sets in every process that it instruments.
MUTANT = "DOKIMI_MUTATE_MUTANT"

#: A generator of byte strings of up to four bytes.
SHORT = Bytes(SequenceBounds(256, 0, 4))

#: The path of the test whose seed files the specs write.
PARSES = ("test_parse.py", "parses")


def no_leading_seven(c: Case) -> None:
    """Fail when the generated byte string starts with 7."""
    data = c.draw(SHORT, "data")
    check.is_false(c, data[:1] == b"\x07", "the data does not start with 7")


def empty(c: Case) -> None:
    """Fail when the generated byte string is not empty."""
    check.is_false(c, len(c.draw(SHORT, "data")) > 0, "the data is empty")


def seeded(directory: Path, files: dict[str, bytes]) -> Recorder:
    """Return a recorder of the test PARSES, with files as its seed files."""
    recorder = Recorder()
    name_test(recorder, PARSES)
    seeds = directory.joinpath("testdata", "fuzz", *PARSES)
    seeds.mkdir(parents=True)
    for name, data in files.items():
        (seeds / name).write_bytes(data)
    return recorder


class TestFuzz:
    """fuzz replays a property and returns the target of a fuzzer."""

    def test_returns_a_target_that_passes_an_input_that_the_body_passes(
        self, seat: Collector
    ) -> None:
        """The data is the byte 1."""
        recorder = Recorder()
        target = fuzz(
            recorder, "no leading seven", no_leading_seven, hermetic(), seed(1)
        )
        check.does_not_raise(seat, lambda: target(bytes([1, 1])), "the input passes")
        check.is_empty(
            seat, recorder.failures, "the replay without stored cases passes"
        )

    def test_returns_a_target_that_returns_for_an_input_whose_case_skips(
        self, seat: Collector
    ) -> None:
        """The fuzzer moves on to the next input."""

        def skips(c: Case) -> None:
            c.draw(SHORT, "data")
            c.skip("unsupported")

        target = fuzz(Recorder(), "skips every input", skips, hermetic(), seed(1))
        check.does_not_raise(seat, lambda: target(bytes([1, 1])), "the input skips")

    def test_hands_the_result_of_each_call_to_the_function_of_on_result(
        self, seat: Collector
    ) -> None:
        """The store is empty, and the target runs one input that passes."""
        results: list[Result] = []
        target = fuzz(
            Recorder(),
            "no leading seven",
            no_leading_seven,
            hermetic(),
            seed(1),
            on_result(results.append),
        )
        target(bytes([1, 1]))
        check.equal(
            seat,
            [[r.outcome, r.cases] for r in results],
            [["passed", 0], ["passed", 1]],
            "the function receives the result of the replay, then of the input",
        )

    def test_returns_a_target_that_raises_the_sentence_of_a_failing_input(
        self, seat: Collector, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """A seed file of the same input fails a recorder with the same sentence."""
        monkeypatch.chdir(tmp_path)
        recorder = seeded(tmp_path, {"a": bytes([2, 7, 7])})
        target = fuzz(
            recorder,
            "no leading seven",
            no_leading_seven,
            hermetic(),
            seed(1),
            store(""),
        )
        error = check.raises(seat, lambda: target(bytes([2, 7, 7])), "the input fails")
        check.equal(
            seat,
            [type(error), str(error)],
            [AssertionError, recorder.message],
            "the error has the sentence of the record",
        )

    def test_fails_the_call_at_a_stored_case_that_fails(
        self, seat: Collector, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The stored case fails as found."""
        monkeypatch.delenv(MUTANT, raising=False)
        directory = str(tmp_path)
        first = Recorder()
        for_all(first, "empty", empty, hermetic(), seed(1), store(directory))
        first.run_cleanups()
        recorder = Recorder()
        fuzz(recorder, "empty", empty, hermetic(), seed(1), store(directory))
        check.equal(
            seat,
            [recorder.failures[0].detail["outcome"], records(recorder)[1]["phase"]],
            ["counterexample", "stored"],
            "the stored case fails as found",
        )

    def test_runs_each_seed_file_of_the_test_as_one_input_of_its_own(
        self, seat: Collector, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The seed file a passes, and the seed file b fails."""
        monkeypatch.chdir(tmp_path)
        recorder = seeded(tmp_path, {"a": bytes([1, 1]), "b": bytes([1, 7])})
        fuzz(
            recorder,
            "no leading seven",
            no_leading_seven,
            hermetic(),
            seed(1),
            store(""),
        )
        check.equal(
            seat,
            [
                [one["verdict"], one["detail"]["outcome"]]
                for one in records(recorder)
                if "parent" not in one
            ],
            [["pass", "passed"], ["pass", "passed"], ["fail", "counterexample"]],
            "the stored cases run before the two seed files",
        )

    def test_returns_a_target_that_raises_the_fault_that_ends_the_call(
        self, seat: Collector, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The profile fast is unknown."""
        monkeypatch.setenv(PROFILE_VARIABLE, "fast")
        recorder = Recorder()
        target = fuzz(recorder, "c", no_leading_seven)
        error = check.raises(seat, lambda: target(b""), "the target raises")
        want = (
            'prop.fuzz: DOKIMI_ASSERT_PROP_PROFILE: "fast" is not one of the '
            "profiles default, ci and campaign"
        )
        check.equal(
            seat,
            [recorder.message, str(error)],
            [want, want],
            "the call and the target have the same fault",
        )

    def test_ends_the_call_with_a_fault_for_seed_files_that_cannot_be_read(
        self, seat: Collector, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The directory of the seed files is a file."""
        monkeypatch.chdir(tmp_path)
        recorder = Recorder()
        name_test(recorder, PARSES)
        parent = tmp_path.joinpath("testdata", "fuzz", PARSES[0])
        parent.mkdir(parents=True)
        (parent / PARSES[1]).write_bytes(b"")
        fuzz(recorder, "c", no_leading_seven, hermetic(), store(""))
        check.has_prefix(
            seat,
            recorder.message,
            f"prop.fuzz: {Path('testdata', 'fuzz', *PARSES)}: the seed "
            "files cannot be read: ",
            "the fault has the path and the reason",
        )
